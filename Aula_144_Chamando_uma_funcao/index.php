<?php

    // Definindo uma função chamada "soma"
    function soma() {
        // Dentro da função "soma", é realizado o cálculo da soma de 4 + 2 e o resultado é exibido
        // com o comando "echo". A string "<br>" é adicionada ao final para criar uma quebra de linha
        // após exibir o resultado.
        $a = 5;
        $b = 4;
        echo $a + $b . "<br>";
    }

    // Chamando a função "soma", o que executa o código dentro dela e exibe o resultado
    soma();

?>
